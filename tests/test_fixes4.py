import pytest

from app import pipeline
from app.profiles import load_profiles

PROFILES = load_profiles()
CHECKER = PROFILES["checker"]


def mask(text: str) -> str:
    return pipeline.apply(text, pipeline.detect(text, CHECKER))


FIO_ROLE_CASES = [
    ("Клиентка Юлия Сергеевна Кузнецова", "Клиентка Ю. С. К."),
    ("Гражданка Анна Петровна Соколова", "Гражданка А. П. С."),
    ("Заявитель Иван Петрович Сидоров", "Заявитель И. П. С."),
    ("клиентка мария кузнецова", "клиентка М. К."),
    ("клиентка александр пушкин", "клиентка А. П."),
    ("поэт Александр Сергеевич Пушкин", "поэт Александр Сергеевич Пушкин"),
    ("клиент иван петров", "клиент И. П."),
    ("держатель карты IVAN IVANOV", "держатель карты I. I."),
]


@pytest.mark.parametrize("text,expected", FIO_ROLE_CASES)
def test_fio_role_not_in_name(text: str, expected: str):
    assert mask(text) == expected



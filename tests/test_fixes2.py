import pytest

from app import pipeline
from app.profiles import load_profiles

PROFILES = load_profiles()
CHECKER = PROFILES["checker"]


def mask(text: str) -> str:
    return pipeline.apply(text, pipeline.detect(text, CHECKER))


FIO_CASES = [
    ("клиент иван петров", "клиент И. П."),
    ("ФИО иван петров", "ФИО И. П."),
    ("заявитель иван петров", "заявитель И. П."),
    ("гражданин иван петров", "гражданин И. П."),
    ("клиент иван петров сидоров", "клиент И. П. С."),
    ("клиент ИВАН ПЕТРОВ", "клиент И. П."),
    ("клиент Иван Петров", "клиент И. П."),
    ("клиент иван петрович сидоров", "клиент И. П. С."),
    ("фамилия иванов", "фамилия И."),
    ("клиент живёт здесь", "клиент живёт здесь"),
    ("клиент живёт в г. Москва и работает в банке",
     "клиент живёт в г. ****** и работает в банке"),
    ("поэт Александр Сергеевич Пушкин", "поэт Александр Сергеевич Пушкин"),
]


@pytest.mark.parametrize("text,expected", FIO_CASES)
def test_fio_lowercase(text: str, expected: str):
    assert mask(text) == expected


ADDRESS_CASES = [
    ("д.10", "д.**"),
    ("г.Москва", "г.******"),
    ("ул.Тверская", "ул.********"),
    ("кв.5", "кв.*"),
    ("корп.2", "корп.*"),
    ("г.Москва, ул.Тверская, д.10, кв.5", "г.******, ул.********, д.**, кв.*"),
    ("дом 10а", "дом ***"),
    ("д. 10А", "д. ***"),
    ("дом 10/2", "дом ****"),
    ("проспект Мира д.10", "проспект **** д.**"),
    ("рядом дом 10 и магазин", "рядом дом ** и магазин"),
    ("и т. д. Продолжение следует", "и т. д. Продолжение следует"),
    ("заказ 123456 готов", "заказ 123456 готов"),
    ("паспорт РФ", "паспорт РФ"),
    ("г. Москва, ул. Тверская, д. 10, кв. 5", "г. ******, ул. ********, д. **, кв. *"),
]


@pytest.mark.parametrize("text,expected", ADDRESS_CASES)
def test_address_no_space(text: str, expected: str):
    assert mask(text) == expected